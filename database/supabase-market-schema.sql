create table if not exists public.kalki_market_checks (
  motorcycle_key text not null,
  part_template_id integer not null,
  provider text not null default 'ebay',
  status text not null,
  result_count integer not null default 0,
  query text,
  error_message text,
  checked_at timestamptz not null default now(),
  primary key(motorcycle_key, part_template_id, provider)
);

alter table public.kalki_market_checks enable row level security;
